func implementMessageValidator(g *protogen.GeneratedFile, m *MessageExt) {
	g.QualifiedGoIdent(protogen.GoIdent{GoName: "protoapi", GoImportPath: ProtoapiModule})
	g.QualifiedGoIdent(protogen.GoIdent{GoName: "context", GoImportPath: "context"})
	g.P("func (x *", g.QualifiedGoIdent(m.GoIdent), ") Validate(set *protoapi.MethodSetting, ctx context.Context) *protoapi.Error {")
	if m.Plugin != nil {
		g.P("if err:=set.MessagePlugin(ctx, x, set.Meta.MessagePlugin); err != nil {")
		g.P("return err")
		g.P("}")
	}
	for i, f := range m.Fields {
		if r := f.Rule; r != nil {
			if r.Required != nil {
				validateRequired(g, i, f)
			}
			if r.Minimum != nil {
				validateMinimum(g, i, f)
			}
			if r.Maximum != nil {
				validateMaximum(g, i, f)
			}
			if r.MinLength != nil {
				validateMinLength(g, i, f)
			}
			if r.MaxLength != nil {
				validateMaxLength(g, i, f)
			}
			if r.MinItems != nil {
				validateMinItems(g, i, f)
			}
			if r.MaxItems != nil {
				validateMaxItems(g, i, f)
			}
			if r.Enum != nil {
				validateEnum(g, i, f)
			}
			if r.Pattern != nil {
				validatePattern(g, i, f)
			}
			if r.Plugin != nil {
				g.P("if err:=set.FieldPlugins[", i, "](ctx, `", f.Name, "`, x.", f.GoName, ", set.Meta.InputRules[", i, "].Plugin); err != nil {")
				g.P("return err")
				g.P("}")
			}
		}
	}
	g.P("return nil")
	g.P("}")
}

func validateRequired(g *protogen.GeneratedFile, i int, f *FieldExt) {
	/*
		required的定义是各值非0值.
	*/
	switch {
	case f.IsRepeated:
		fallthrough
	case f.IsMap:
		g.P("if x.", f.GoName, " == nil {")
		g.P("return set.Meta.InputRules[", i, "].Required")
		g.P("}")
	default:
		switch f.Kind {
		case protoreflect.BoolKind:
			if f.HasOptional {
				g.P("if x.", f.GoName, " == nil {")
				g.P("return set.Meta.InputRules[", i, "].Required")
				g.P("}")
			}
		case protoreflect.EnumKind:
			if f.HasOptional {
				g.P("if x.", f.GoName, " == nil {")
				g.P("return set.Meta.InputRules[", i, "].Required")
				g.P("}")
			}
		case protoreflect.Int32Kind, protoreflect.Sint32Kind, protoreflect.Sfixed32Kind,
			protoreflect.Uint32Kind, protoreflect.Fixed32Kind,
			protoreflect.Int64Kind, protoreflect.Sint64Kind, protoreflect.Sfixed64Kind,
			protoreflect.Uint64Kind, protoreflect.Fixed64Kind,
			protoreflect.FloatKind, protoreflect.DoubleKind:
			if f.HasOptional {
				g.P("if x.", f.GoName, " == nil {")
				g.P("return set.Meta.InputRules[", i, "].Required")
				g.P("}")
			}
		case protoreflect.StringKind:
			if f.HasOptional {
				g.P("if x.", f.GoName, " == nil {")
				g.P("return set.Meta.InputRules[", i, "].Required")
				g.P("}")
			} else {
				g.P("if x.", f.GoName, " == `` {")
				g.P("return set.Meta.InputRules[", i, "].Required")
				g.P("}")
			}
		case protoreflect.BytesKind:
			g.P("if x.", f.GoName, " == nil {")
			g.P("return set.Meta.InputRules[", i, "].Required")
			g.P("}")
		case protoreflect.MessageKind:
			fallthrough
		case protoreflect.GroupKind:
			g.P("if x.", f.GoName, " == nil {")
			g.P("return set.Meta.InputRules[", i, "].Required")
			g.P("}")
		}
	}
}

func validateMinimum(g *protogen.GeneratedFile, i int, f *FieldExt) {
	/*
		minimum针对enum/number类型. 其他类型自动忽略
	*/
	switch {
	case f.IsRepeated:
	case f.IsMap:
	default:
		switch f.Kind {
		case protoreflect.BoolKind:
		case protoreflect.EnumKind:
			fallthrough
		case protoreflect.Int32Kind, protoreflect.Sint32Kind, protoreflect.Sfixed32Kind,
			protoreflect.Uint32Kind, protoreflect.Fixed32Kind,
			protoreflect.Int64Kind, protoreflect.Sint64Kind, protoreflect.Sfixed64Kind,
			protoreflect.Uint64Kind, protoreflect.Fixed64Kind,
			protoreflect.FloatKind, protoreflect.DoubleKind:
			if f.HasOptional {
				// 只比较非nil值, 否则nil算是上界, 还是下界? 扯开了难有定论
				g.P("if x.", f.GoName, " != nil {")
				if f.Rule.Minimum.Exclusive {
					g.P("if *x.", f.GoName, " <= ", f.Rule.Minimum.Val, " {")
					g.P("return set.Meta.InputRules[", i, "].Minimum.Err")
					g.P("}")
				} else {
					g.P("if *x.", f.GoName, " < ", f.Rule.Minimum.Val, " {")
					g.P("return set.Meta.InputRules[", i, "].Minimum.Err")
					g.P("}")
				}
				g.P("}")
			} else {
				if f.Rule.Minimum.Exclusive {
					g.P("if x.", f.GoName, " <= ", f.Rule.Minimum.Val, " {")
					g.P("return set.Meta.InputRules[", i, "].Minimum.Err")
					g.P("}")
				} else {
					g.P("if x.", f.GoName, " < ", f.Rule.Minimum.Val, " {")
					g.P("return set.Meta.InputRules[", i, "].Minimum.Err")
					g.P("}")
				}
			}
		case protoreflect.StringKind:
		case protoreflect.BytesKind:
		case protoreflect.MessageKind:
		case protoreflect.GroupKind:
		}
	}
}

