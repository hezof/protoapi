const ProtoapiModule = `github.com/hezof/protoapi`

// generateCodeFile 生成实现文件: *_protoapi.pb.go
func generateImplFile(gen *protogen.Plugin, file *protogen.File, meta *FileExt) {

	g := gen.NewGeneratedFile(file.GeneratedFilenamePrefix+`_protoapi.pb.go`, file.GoImportPath)

	protocVersion := "(unknown)"
	if v := gen.Request.GetCompilerVersion(); v != nil {
		protocVersion = fmt.Sprintf("v%v.%v.%v", v.GetMajor(), v.GetMinor(), v.GetPatch())
	}

	// 1. 输出头部
	g.P("// Code generated by protoc-gen-go-protoapi. DO NOT EDIT!")
	g.P("// versions:")
	g.P("// - protoc-gen-go-protoapi ", version) // 与依赖的protobuf版本相同
	g.P("// - protoc                 ", protocVersion)
	g.P("// source: ", meta.Path)
	g.P("// create: ", time.Now().Format("2006-01-02 15:04:05"))
	g.P()
	g.P("package ", meta.GoPackage)
	g.P()

	// 2. 输出message(local)的JsonCodec及MessageValidator实现
	for _, m := range meta.Messages.Vec {
		if m.FilePath == meta.Path {
			implementJsonCodec(g, m)
			if shouldMessageValidator(m) {
				implementMessageValidator(g, m)
			}
		}
	}

	// 3. 输出service(local)的ServiceRegistry实现
	for _, s := range meta.Services {
		if s.FilePath == meta.Path {
			implementServiceRegistry(g, s)
		}
	}
}

func implementJsonCodec(g *protogen.GeneratedFile, m *MessageExt) {
	g.QualifiedGoIdent(protogen.GoIdent{GoName: "protoapi", GoImportPath: ProtoapiModule})
	g.P("func (x *", g.QualifiedGoIdent(m.GoIdent), ") DecodeJSON(r *protoapi.JsonDecoder) {")
	g.P("protoapi.DecodeMessage(r, &x, func(r *protoapi.JsonDecoder, x *", g.QualifiedGoIdent(m.GoIdent), ", k string) {")
	g.P("switch k {")
	for _, f := range m.Fields {
		g.P("case `", fname(f), "`:")
		
	}
	g.P("}")  // switch
	g.P("})") // protoapi.DecodeMessage
	g.P("}")  // func
	g.P("func (x *", g.QualifiedGoIdent(m.GoIdent), ") EncodeJSON(w *protoapi.JsonEncoder) {")

	g.P("}")
}

func implementMessageValidator(g *protogen.GeneratedFile, m *MessageExt) {
	g.QualifiedGoIdent(protogen.GoIdent{GoName: "protoapi", GoImportPath: ProtoapiModule})
	g.QualifiedGoIdent(protogen.GoIdent{GoName: "context", GoImportPath: "context"})
	g.P("func (x *", g.QualifiedGoIdent(m.GoIdent), ") Validate(set *protoapi.MethodSetting, ctx context.Context) *protoapi.Error {")
	if m.Plugin != nil {
		g.P("if err:=set.MessagePlugin(ctx, x, set.Meta.MessagePlugin); err != nil {")
		g.P("return err")
		g.P("}")
	}
	for i, f := range m.Fields {
		if r := f.Rule; r != nil {
			if r.Required != nil {
				validateRequired(g, i, f)
			}
			if r.Minimum != nil {
				validateMinimum(g, i, f)
			}
			if r.Maximum != nil {
				validateMaximum(g, i, f)
			}
			if r.MinLength != nil {
				validateMinLength(g, i, f)
			}
			if r.MaxLength != nil {
				validateMaxLength(g, i, f)
			}
			if r.MinItems != nil {
				validateMinItems(g, i, f)
			}
			if r.MaxItems != nil {
				validateMaxItems(g, i, f)
			}
			if r.Enum != nil {
				validateEnum(g, i, f)
			}
			if r.Pattern != nil {
				validatePattern(g, i, f)
			}
			if r.Plugin != nil {
				g.P("if err:=set.FieldPlugins[", i, "](ctx, `", f.Name, "`, x.", f.GoName, ", set.Meta.InputRules[", i, "].Plugin); err != nil {")
				g.P("return err")
				g.P("}")
			}
		}
	}
	g.P("return nil")
	g.P("}")
}

