func shouldMessageValidator(m *MessageExt) bool {
	if m.Plugin != nil {
		return true
	}
	for _, f := range m.Fields {
		if r := f.Rule; r != nil {
			if r.Required != nil {
				return true
			}
			if r.Minimum != nil {
				return true
			}
			if r.Maximum != nil {
				return true
			}
			if r.MinLength != nil {
				return true
			}
			if r.MaxLength != nil {
				return true
			}
			if r.MinItems != nil {
				return true
			}
			if r.MaxItems != nil {
				return true
			}
			if r.Enum != nil {
				return true
			}
			if r.Pattern != nil {
				return true
			}
			if r.Plugin != nil {
				return true
			}
		}
	}
	return false
}
